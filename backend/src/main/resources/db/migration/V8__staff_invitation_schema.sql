        CREATE UNIQUE INDEX idx_uq_lab_mgr_invitation ON StaffInvitation(institution_id, department_id, role_name)
        WHERE role_name = 'LAB_MANAGER' AND status IN ('PENDING', 'ACCEPTED');
    END IF;
END $$;
